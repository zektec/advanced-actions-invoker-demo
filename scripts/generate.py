"""Generate dispatch workflows from Composer-compatible configuration files."""
import argparse
import json
from pathlib import Path

import yaml
from jsonschema import Draft7Validator, FormatChecker

ROOT = Path(__file__).resolve().parents[1]
CHECKOUT = "actions/checkout@11d5960a326750d5838078e36cf38b85af677262"
PYTHON = "actions/setup-python@a26af69be951a213d495a4c3e4e4022e16d87065"
PARSER = "zektec/advanced-actions-invoker-utils@291d2a5e075450f32cba22ea1584a2cd84a60f2c"  # v1.0.0
ARTIFACT = "actions/upload-artifact@ea165f8d65b6e75b540449e92b4886f43607fa02"


def validate_config(config):
    Draft7Validator.check_schema(config["schema"])
    Draft7Validator(config["schema"], format_checker=FormatChecker(formats=["date", "time", "email", "uri"])).validate(config["data"])

    def visit(node):
        if node["type"] == "Control":
            assert node["scope"].startswith("#/properties/")
            target = config["schema"]
            for token in node["scope"][2:].split("/"):
                target = target[token.replace("~1", "/").replace("~0", "~")]
        else:
            assert node["type"] in {"VerticalLayout", "HorizontalLayout", "Group"}
            for child in node["elements"]:
                visit(child)
    visit(config["uischema"])


def workflow(slug, config):
    validate_config(config)
    inputs = {}
    for key, source, description in [
        ("schema", "schema", "JSON Schema — leave unchanged"),
        ("layout", "uischema", "JSON Forms layout — leave unchanged"),
        ("data", "data", "Form values (JSON without the extension)"),
    ]:
        inputs[key] = {"description": description, "type": "string", "required": True,
                       "default": json.dumps(config[source], separators=(",", ":"))}
    return {
        "name": config["name"],
        "on": {"workflow_dispatch": {"inputs": inputs}},
        "permissions": {"contents": "read"},
        "jobs": {"demo": {
            "runs-on": "warp-ubuntu-2404-x64-4x", "timeout-minutes": 5,
            "steps": [
                {"uses": CHECKOUT},
                {"uses": PYTHON, "with": {"python-version": "3.12"}},
                {"name": "Install validators", "run": "python -m pip install -r requirements.txt"},
                {"name": "Parse form inputs", "id": "form", "uses": PARSER,
                 "with": {"schema": "${{ inputs.schema }}", "layout": "${{ inputs.layout }}",
                          "data": "${{ inputs.data }}"}},
                {"name": "Validate and create demo plan",
                 "env": {"DEMO_DATA": "${{ inputs.data }}",
                         "DEMO_PARSED_OUTPUTS": "${{ toJSON(steps.form.outputs) }}"},
                 "run": f"python scripts/run_demo.py {slug}"},
                {"name": "Downloadable demo plan", "uses": ARTIFACT,
                 "with": {"name": f"{slug}-plan", "path": "demo-plan.json", "retention-days": 7}},
            ],
        }},
    }


def generate(check=False):
    for file in sorted((ROOT / "examples").glob("*.json")):
        config = json.loads(file.read_text())
        result = "# Generated by scripts/generate.py; edit examples/ instead.\n" + yaml.safe_dump(
            workflow(file.stem, config), sort_keys=False, width=100000, allow_unicode=True)
        target = ROOT / ".github/workflows" / f"{file.stem}.yml"
        if check:
            assert target.exists() and target.read_text() == result, f"Regenerate {target.name}"
        else:
            target.write_text(result)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    generate(parser.parse_args().check)
